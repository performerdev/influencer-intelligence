"""
Trace the brain every intelligence is drawn with from a reference picture.

    python3 scripts/brain-shape.py reference.png   # RGBA, transparent background, brain in side view on the left

Writes apps/web/lib/brain-shape.ts: a grid over the silhouette with three layers
  h  half-thickness of the silhouette inflated into 3D (lap f = -2, h = sqrt f → round cross-sections)
  s  the picture's gyri: brightness with the LED grid blurred away, 0 = groove … 255 = ridge
  g  0 = one tube (brainstem) … 255 = two hemispheres with the fissure between them
apps/web/lib/brain-model.ts turns that into the 3D point cloud.

Needs numpy, scipy, pillow.
"""
import base64
import sys
from pathlib import Path

import numpy as np
from PIL import Image
from scipy import ndimage as ndi

GW = 96  # cells along the brain
HALF_WIDTH = 0.70  # widest half-thickness, in half-lengths

src = sys.argv[1]
out = Path(__file__).resolve().parent.parent / "apps/web/lib/brain-shape.ts"

a = np.asarray(Image.open(src).convert("RGBA")).astype(np.float32) / 255
a = a[:, : a.shape[1] // 2]  # the left brain
A = a[..., 3]
L = a[..., :3].max(axis=2)

ys, xs = np.where(A > 0.3)
pad = 6
y0, x0 = max(0, ys.min() - pad), max(0, xs.min() - pad)
y1, x1 = min(A.shape[0], ys.max() + 1 + pad), min(A.shape[1], xs.max() + 1 + pad)
A, L = A[y0:y1, x0:x1], L[y0:y1, x0:x1]
bh, bw = A.shape
GH = round(GW * bh / bw)


def down(img):
    return np.asarray(Image.fromarray(img.astype(np.float32), mode="F").resize((GW, GH), Image.BOX))


# silhouette: the LED cells' alpha, smoothed, largest blob, no holes
mask = down(ndi.gaussian_filter(A, 7)) > 0.12
mask = ndi.binary_fill_holes(mask)
lab, n = ndi.label(mask)
mask = lab == (1 + int(np.argmax(ndi.sum(mask, lab, range(1, n + 1)))))
mask = ndi.binary_fill_holes(ndi.binary_opening(mask, iterations=1) | (mask & ndi.binary_erosion(mask)))

# gyri
num = ndi.gaussian_filter(L * A, 9)
den = ndi.gaussian_filter(A, 9) + 1e-4
S = down(num / den)
lo, hi = np.percentile(S[mask], 4), np.percentile(S[mask], 97)
S = np.clip((S - lo) / (hi - lo), 0, 1)

# inflate
f = np.zeros((GH, GW))
for _ in range(4000):
    nb = np.zeros_like(f)
    nb[1:, :] += f[:-1, :]
    nb[:-1, :] += f[1:, :]
    nb[:, 1:] += f[:, :-1]
    nb[:, :-1] += f[:, 1:]
    f = np.where(mask, (nb + 2) / 4, 0)
h = np.sqrt(np.maximum(f, 0))
hz = h * HALF_WIDTH / h.max()
g = np.clip((ndi.maximum_filter(hz, size=15) - 0.25) / 0.3, 0, 1)

ZMAX = float(hz.max())
layer = lambda v: base64.b64encode(v.astype(np.uint8).tobytes()).decode()
H = np.where(mask, np.maximum(1, np.round(hz / ZMAX * 255)), 0)
out.write_text(
    f'''/**
 * The brain's shape, traced from the reference picture (a pixel brain in side
 * view): a {GW}×{GH} grid, generated by scripts/brain-shape.py. Don't edit by hand.
 *
 * h: half-thickness of the inflated silhouette, 0 = outside (× ZMAX / 255)
 * s: the picture's gyri, 0 = groove … 255 = ridge
 * g: 0 = one tube (brainstem) … 255 = two hemispheres with a fissure between them
 */
export const BRAIN_GW = {GW};
export const BRAIN_GH = {GH};
export const BRAIN_ZMAX = {round(ZMAX, 4)};
export const BRAIN_H = "{layer(H)}";
export const BRAIN_S = "{layer(np.where(mask, np.round(S * 255), 0))}";
export const BRAIN_G = "{layer(np.where(mask, np.round(g * 255), 0))}";
'''
)
print(f"wrote {out} ({GW}x{GH}, {int(mask.sum())} cells)")
